/**
 * Normalizes input string for search comparisons (lowercase, removes special chars)
 */
function normalizeQuery(str: string): string {
  return str
    .toLowerCase()
    .replace(/[^\w\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Open search inside CPU or GPU database with intelligent scoring
 */
export function searchHardware(
  query: string,
  type: 'gpu' | 'cpu',
  limit = 8
): HardwareItem[] {
  const database = type === 'gpu' ? GPUS_DATABASE : CPUS_DATABASE;
  if (!query || query.trim().length === 0) {
    // Return most popular modern components when empty
    return database.slice(0, limit);
  }

  const cleanQuery = normalizeQuery(query);
  const terms = cleanQuery.split(' ').filter(Boolean);

  // Score each item based on matches
  const scoredItems = database
    .map((item) => {
      let matchScore = 0;
      const cleanName = normalizeQuery(item.name);
      const cleanAliases = item.aliases.map(normalizeQuery);

      // Exact alias match
      if (cleanAliases.includes(cleanQuery)) {
        matchScore += 200;
      }

      // Starts with query
      if (cleanName.startsWith(cleanQuery)) {
        matchScore += 100;
      }

      // Exact substring match in name
      if (cleanName.includes(cleanQuery)) {
        matchScore += 70;
      }

      // Alias substring match
      for (const alias of cleanAliases) {
        if (alias.includes(cleanQuery)) {
          matchScore += 50;
          break;
        }
      }

      // Every term present
      const allTermsPresent = terms.every(
        (term) => cleanName.includes(term) || cleanAliases.some((a) => a.includes(term))
      );

      if (allTermsPresent) {
        matchScore += 40 * terms.length;
      } else {
        // Partial terms
        const matchedTerms = terms.filter(
          (term) => cleanName.includes(term) || cleanAliases.some((a) => a.includes(term))
        );
        matchScore += 10 * matchedTerms.length;
      }

      return { item, matchScore };
    })
    .filter((entry) => entry.matchScore > 0)
    .sort((a, b) => b.matchScore - a.matchScore);

  return scoredItems.slice(0, limit).map((entry) => entry.item);
}

/**
 * Finds exact or best matching hardware item from user query string
 */
export function findHardwareByNameOrAlias(
  query: string,
  type: 'gpu' | 'cpu'
): HardwareItem | null {
  if (!query || query.trim().length === 0) return null;

  const database = type === 'gpu' ? GPUS_DATABASE : CPUS_DATABASE;
  const cleanQ = normalizeQuery(query);

  // 1. Exact match on id or exact name
  const exact = database.find(
    (item) => item.id === query || normalizeQuery(item.name) === cleanQ
  );
  if (exact) return exact;

  // 2. Exact match in aliases
  const aliasMatch = database.find((item) =>
    item.aliases.some((alias) => normalizeQuery(alias) === cleanQ)
  );
  if (aliasMatch) return aliasMatch;

  // 3. Search top result if confidence is high
  const results = searchHardware(query, type, 3);
  if (results.length > 0) {
    return results[0];
  }

  return null;
}

/**
 * Fallback parser in case the user typed a custom string that was not found in database.
 * Never fails: estimates a realistic score and tier from keywords!
 */
export function fallbackEstimateHardware(
  rawText: string,
  type: 'gpu' | 'cpu'
): { score: number; tier: 'Bajo' | 'Medio' | 'Alto' | 'Ultra'; name: string; vramGb?: number } {
  const text = rawText.toLowerCase();

  if (type === 'gpu') {
    // Ultra
    if (text.includes('4090') || text.includes('4080') || text.includes('7900')) {
      return { score: 14000, tier: 'Ultra', name: rawText, vramGb: 16 };
    }
    // Alto
    if (
      text.includes('4070') ||
      text.includes('3080') ||
      text.includes('3070') ||
      text.includes('6800') ||
      text.includes('7800') ||
      text.includes('7700') ||
      text.includes('b580') ||
      text.includes('a770')
    ) {
      return { score: 10000, tier: 'Alto', name: rawText, vramGb: 12 };
    }
    // Medio
    if (
      text.includes('4060') ||
      text.includes('3060') ||
      text.includes('2060') ||
      text.includes('2070') ||
      text.includes('1070') ||
      text.includes('1080') ||
      text.includes('1660') ||
      text.includes('6600') ||
      text.includes('5700') ||
      text.includes('580') ||
      text.includes('590') ||
      text.includes('vega 56')
    ) {
      return { score: 6200, tier: 'Medio', name: rawText, vramGb: 8 };
    }
    // Bajo / Integrada
    if (
      text.includes('1050') ||
      text.includes('1650') ||
      text.includes('750') ||
      text.includes('550') ||
      text.includes('560') ||
      text.includes('vega') ||
      text.includes('iris') ||
      text.includes('uhd') ||
      text.includes('hd graphics') ||
      text.includes('intel')
    ) {
      return { score: 2200, tier: 'Bajo', name: rawText, vramGb: 2 };
    }

    // Default safe guess
    return { score: 3500, tier: 'Bajo', name: rawText, vramGb: 4 };
  } else {
    // CPU fallback
    if (
      text.includes('14900') ||
      text.includes('13900') ||
      text.includes('7950') ||
      text.includes('9800x3d') ||
      text.includes('7800x3d')
    ) {
      return { score: 15500, tier: 'Ultra', name: rawText };
    }
    if (
      text.includes('14700') ||
      text.includes('13700') ||
      text.includes('12700') ||
      text.includes('7700') ||
      text.includes('5800') ||
      text.includes('5900') ||
      text.includes('7600') ||
      text.includes('13600') ||
      text.includes('14600') ||
      text.includes('12600')
    ) {
      return { score: 11000, tier: 'Alto', name: rawText };
    }
    if (
      text.includes('5600') ||
      text.includes('3600') ||
      text.includes('3700') ||
      text.includes('12400') ||
      text.includes('10400') ||
      text.includes('11400') ||
      text.includes('8700') ||
      text.includes('9700') ||
      text.includes('i7')
    ) {
      return { score: 7500, tier: 'Medio', name: rawText };
    }
    if (
      text.includes('i5') ||
      text.includes('i3') ||
      text.includes('ryzen 3') ||
      text.includes('fx') ||
      text.includes('phenom') ||
      text.includes('core 2')
    ) {
      return { score: 3800, tier: 'Bajo', name: rawText };
    }

    return { score: 4500, tier: 'Bajo', name: rawText };
  }
}
